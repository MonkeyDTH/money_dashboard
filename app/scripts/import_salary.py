def build_items(row: dict, record_id: int) -> list[SalaryItem]:
    items = []

    def add(item_type: ItemType, direction: Direction, label: str, raw_val):
        val = to_dec(raw_val)
        if val is None:
            return
        amount = abs(val)
        if amount == 0:
            return
        items.append(SalaryItem(
            salary_record_id=record_id,
            item_type=item_type,
            direction=direction,
            label=label,
            amount=amount,
        ))

    add(ItemType.base,             Direction.income,    "合同工资",     row["合同工资"])
    add(ItemType.bonus,            Direction.income,    "奖金",         row["奖金"])
    add(ItemType.allowance,        Direction.income,    "补贴",         row["补贴"])
    add(ItemType.social_insurance, Direction.deduction, "五险一金（个人）", row["五险一金个人"])
    add(ItemType.income_tax,       Direction.deduction, "个税",         row["个税扣除"])
    add(ItemType.housing_fund,     Direction.income,    "公积金充值",   row["公积金充值"])

    return items


def run():
    init_db()

    with Session(engine) as session:
        # 创建或获取公司
        company_map: dict[str, int] = {}
        for feishu_name, db_name, start, end in COMPANY_DEFS:
            existing = session.exec(
                select(Company).where(Company.name == db_name).where(Company.member_id == MEMBER_ID)
            ).first()
            if existing:
                company_map[feishu_name] = existing.id
                print(f"公司已存在：{db_name} (id={existing.id})")
            else:
                c = Company(name=db_name, member_id=MEMBER_ID, start_date=start, end_date=end)
                session.add(c)
                session.flush()
                company_map[feishu_name] = c.id
                print(f"新建公司：{db_name} (id={c.id})")

        inserted = skipped = 0
        for row in RAW_RECORDS:
            pay_date = date.fromisoformat(row["日期"])
            period = month_end(pay_date)
            company_id = company_map[row["公司"]]
            net = Decimal(str(row["实际到手"]))

            # 计算 gross（所有收入项之和）
            income_fields = [row["合同工资"], row["奖金"], row["补贴"]]
            gross = sum(Decimal(str(v)) for v in income_fields if v is not None and v != 0)

            # 幂等检查：同公司同 period 的 SalaryRecord
            existing = session.exec(
                select(SalaryRecord)
                .where(SalaryRecord.company_id == company_id)
                .where(SalaryRecord.period == period)
                .where(SalaryRecord.pay_date == pay_date)
            ).first()
            if existing:
                print(f"跳过（已存在）：{row['公司']} {period}")
                skipped += 1
                continue

            rec = SalaryRecord(
                member_id=MEMBER_ID,
                company_id=company_id,
                period=period,
                pay_date=pay_date,
                gross=gross,
                net=net,
                note=row["备注"],
            )
            session.add(rec)
            session.flush()

            items = build_items(row, rec.id)
            for item in items:
                session.add(item)

            inserted += 1

        session.commit()
        print(f"\n导入完成：新增 {inserted} 条薪资记录，跳过 {skipped} 条")


if __name__ == "__main__":
    run()
